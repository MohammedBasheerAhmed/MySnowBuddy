// Report generation and file export.
//
// Everything here is pure string building plus a Blob download, so it works
// identically from the sidebar (content script) and the options page.

function timestamp() {
  return new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
}

/** Trigger a browser download of `blob` as `filename`. */
export function downloadBlob(filename, blob) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.style.display = 'none';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  // Revoke on the next tick so the download has committed to the URL.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Trigger a browser download of `text` as `filename`. */
export function downloadText(filename, text, mimeType = 'text/markdown') {
  downloadBlob(filename, new Blob([text], { type: `${mimeType};charset=utf-8` }));
}

export function suggestFilename(prefix, extension = 'md') {
  return `mysnowbuddy-${prefix}-${timestamp()}.${extension}`;
}

/**
 * Render an instance comparison result as a change-advisory-ready markdown
 * document.
 */
export function compareResultToMarkdown(result, aiSummary = '') {
  if (!result) return '';

  const lines = [
    `# Instance comparison: ${result.label || result.table}`,
    '',
    `| | |`,
    `| --- | --- |`,
    `| Source | ${result.source} |`,
    `| Target | ${result.target} |`,
    `| Table | \`${result.table}\` |`,
    `| Generated | ${new Date().toISOString()} |`,
    '',
    '## Summary',
    '',
    `- Only in source: **${result.counts?.added ?? result.added.length}**`,
    `- Only in target: **${result.counts?.removed ?? result.removed.length}**`,
    `- Differing: **${result.counts?.modified ?? result.modified.length}**`,
    '',
  ];

  if (aiSummary) {
    lines.push('## AI risk analysis', '', aiSummary, '');
  }

  if (result.added?.length) {
    lines.push(`## Only in source (${result.source})`, '');
    result.added.forEach((item) => lines.push(`- \`${item.key || item.name}\``));
    lines.push('');
  }

  if (result.removed?.length) {
    lines.push(`## Only in target (${result.target})`, '');
    result.removed.forEach((item) => lines.push(`- \`${item.key || item.name}\``));
    lines.push('');
  }

  if (result.modified?.length) {
    lines.push('## Differing records', '');
    result.modified.forEach((item) => {
      lines.push(`### ${item.key || item.name}`, '');
      (item.fieldDiffs || []).forEach((diff) => {
        lines.push(`**${diff.field}**`, '', '```diff', diff.diffText || '(no textual diff)', '```', '');
      });
    });
  }

  lines.push(
    '---',
    '',
    '_Generated by NowBuddy. Diffs are line-based; review in the instance before deploying._'
  );

  return lines.join('\n');
}

/** Render lint findings as markdown. */
export function lintFindingsToMarkdown(findings, context = {}) {
  const lines = [
    '# Code review findings',
    '',
    `- Table: \`${context.table || 'unknown'}\``,
    `- Field: \`${context.fieldName || 'script'}\``,
    `- Generated: ${new Date().toISOString()}`,
    '',
  ];

  if (!findings.length) {
    lines.push('No issues found by the deterministic rules.');
    return lines.join('\n');
  }

  lines.push('| Severity | Line | Rule | Issue |', '| --- | --- | --- | --- |');
  findings.forEach((f) => {
    lines.push(`| ${f.severity} | ${f.line} | \`${f.ruleId}\` | ${f.message.replace(/\|/g, '\\|')} |`);
  });
  lines.push('');

  findings.forEach((f) => {
    lines.push(
      `### Line ${f.line} - ${f.message}`,
      '',
      '```javascript',
      f.lineText,
      '```',
      '',
      `**Fix:** ${f.suggestion}`,
      ''
    );
  });

  return lines.join('\n');
}

/** Render security audit findings as markdown. */
export function auditToMarkdown(result) {
  const lines = [
    '# ServiceNow security audit',
    '',
    `Generated: ${new Date().toISOString()}`,
    '',
    '## Scope',
    '',
    'Read-only review of configuration readable by the signed-in user. No ACLs were bypassed.',
    '',
    '## Findings',
    '',
  ];

  if (!result.findings.length) {
    lines.push('No findings from the deterministic checks.');
  } else {
    lines.push('| Severity | Category | Finding |', '| --- | --- | --- |');
    result.findings.forEach((f) => {
      lines.push(`| ${f.severity} | ${f.category} | ${f.message.replace(/\|/g, '\\|')} |`);
    });
    lines.push('', '## Detail', '');
    result.findings.forEach((f) => {
      lines.push(`### [${f.severity.toUpperCase()}] ${f.message}`, '', f.detail, '');
      if (f.link) lines.push(`Record: \`${f.link}\``, '');
    });
  }

  if (result.errors?.length) {
    lines.push('## Checks that could not run', '');
    result.errors.forEach((e) => lines.push(`- ${e.check}: ${e.error}`));
  }

  return lines.join('\n');
}

/** Render code search results as markdown. */
export function searchResultsToMarkdown(search) {
  const lines = [
    `# Code search: \`${search.term}\``,
    '',
    `${search.totalMatches} match(es) across ${search.totalRecords} record(s) in ${search.scannedTables} table(s).`,
    `Generated: ${new Date().toISOString()}`,
    '',
  ];

  search.results.forEach((result) => {
    lines.push(`## ${result.label}: ${result.name}`, '', `- Table: \`${result.table}\``, `- Field: \`${result.field}\``, '');
    result.matches.forEach((m) => {
      lines.push(`\`${String(m.lineNumber).padStart(4)}\` \`${m.text.replace(/`/g, "'")}\``);
    });
    lines.push('');
  });

  if (search.errors?.length) {
    lines.push('## Tables that could not be searched', '');
    search.errors.forEach((e) => lines.push(`- ${e.label} (\`${e.table}\`): ${e.error}`));
  }

  return lines.join('\n');
}

/** Render update set analysis as markdown. */
export function updateSetToMarkdown({ selectedSet, collisions, uncaptured, days }) {
  const lines = [
    '# Update set deployment review',
    '',
    `Generated: ${new Date().toISOString()}`,
    '',
  ];

  if (selectedSet) {
    lines.push(`## Update set`, '', `- Name: **${selectedSet.name}**`, `- State: ${selectedSet.state}`, '');
  }

  lines.push(`## Collisions (${collisions?.length || 0})`, '');
  if (collisions?.length) {
    lines.push('| Artifact | Type | Also in |', '| --- | --- | --- |');
    collisions.forEach((c) => {
      const others = c.conflictsWith.map((o) => `${o.updateSetName} (${o.updateSetState})`).join('<br>');
      lines.push(`| ${c.targetName || c.name} | ${c.type} | ${others} |`);
    });
  } else {
    lines.push('None detected.');
  }
  lines.push('');

  lines.push(`## Uncaptured changes in the last ${days || 7} days (${uncaptured?.length || 0})`, '');
  if (uncaptured?.length) {
    lines.push('| Type | Record | Changed | By |', '| --- | --- | --- | --- |');
    uncaptured.forEach((u) => {
      lines.push(`| ${u.label} | ${u.name} | ${u.updatedOn} | ${u.updatedBy} |`);
    });
  } else {
    lines.push('None detected.');
  }

  return lines.join('\n');
}
